#!/usr/bin/env python3
"""
model_gate.py — rule 30 as CODE, not as prose in a markdown file.

Rule 30 was written into skills/betting/global_heuristics.md, labelled BLOCKING,
and enforced nowhere. A rule that lives only in a prompt is a suggestion: the
engine went on emitting standalone model selections exactly as before. This
module is the actual gate.

The finding it enforces (data/market_validation.json, measured 2026-08-22):
soccer 1X2, tennis ATP and tennis WTA all LOSE to the market price, the market
is better calibrated than the model in every case, and market_anchor.py fitted
the model's blend weight to 0.00 out-of-sample. A selection generated by one of
those models, on its own, is a bet with negative expectation.

So: a sport whose model has been measured against real prices and FAILED cannot
produce a standalone selection. It can still describe, compare and shortlist —
those do not stake money.

Deliberately conservative in both directions:
  * A sport with NO measurement is NOT blocked. Absence of evidence is not
    evidence of failure, and silently blocking everything would make the gate
    useless and invite someone to switch it off.
  * A sport that FAILED is blocked until a re-run says otherwise. Clearing it
    requires re-running the backtest, not editing a constant here.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

DATA = Path(__file__).parent.parent / "data"
VALIDATION = DATA / "market_validation.json"

# Which validation entry governs which sport.
_SPORT_KEYS = {
    "SOCCER": ("soccer_close",),
    "TENNIS": ("tennis_atp", "tennis_wta"),
}
_CACHE: Optional[dict] = None


def _load() -> dict:
    global _CACHE
    if _CACHE is None:
        try:
            _CACHE = json.loads(VALIDATION.read_text())
        except (FileNotFoundError, OSError, json.JSONDecodeError):
            _CACHE = {}
    return _CACHE


def status(sport: str) -> dict:
    """Has this sport's model been measured against real prices, and did it pass?"""
    res = (_load().get("results") or {})
    keys = _SPORT_KEYS.get((sport or "").upper(), ())
    entries = [(k, res[k]) for k in keys if k in res]
    if not entries:
        return {"sport": sport, "measured": False, "passed": None,
                "standalone_allowed": True,
                "reason": "no market validation on file for this sport — not "
                          "blocked, but not proven either"}

    failures = []
    for k, e in entries:
        vm = e.get("vs_market") or {}
        mb, kb = vm.get("model_brier"), vm.get("market_brier")
        roi = (e.get("betting") or {}).get("roi")
        if roi is None:
            roi = e.get("roi")
        beat = (mb is not None and kb is not None and mb < kb)
        if not beat or (roi is not None and roi <= 0):
            failures.append({"test": k, "model_brier": mb, "market_brier": kb,
                             "roi": roi})
    passed = not failures
    return {
        "sport": sport, "measured": True, "passed": passed,
        "standalone_allowed": passed,
        "failures": failures,
        "reason": ("model beats the price in every measured test"
                   if passed else
                   "model LOSES to the market price — a standalone selection "
                   "from it is negative expectation (rule 30)"),
    }


def allows_standalone(sport: str) -> bool:
    return bool(status(sport)["standalone_allowed"])


def gate(sport: str, payload: dict) -> dict:
    """Stamp a prediction, and neutralise its call to action if it is blocked.

    The numbers are left intact — they are still useful for comparison and
    description. What is removed is the instruction to bet.
    """
    st = status(sport)
    out = {**payload, "model_gate": st}
    if st["standalone_allowed"]:
        return out
    sig = payload.get("bet_signal")
    if sig not in (None, "NO_DATA", "NO_BET"):
        out["bet_signal_model"] = sig          # keep what the model said
        out["bet_signal"] = "NO_BET_MODEL_UNVALIDATED"
    out["edge_strength"] = "BLOCKED"
    out["gate_note"] = (
        "Numbers shown for comparison only. This sport's model was measured "
        "against real prices and lost, so it does not issue standalone picks. "
        "Shop the price instead (line_shop.py)."
    )
    return out


def filter_candidates(candidates: list[dict], sport_key: str = "sport") -> tuple:
    """Drop candidates whose sport is blocked. Returns (kept, dropped)."""
    kept, dropped = [], []
    for c in candidates:
        sp = c.get(sport_key) or c.get("sport") or ""
        (kept if allows_standalone(sp) else dropped).append(c)
    return kept, dropped


if __name__ == "__main__":
    import sys
    for s in (sys.argv[1:] or ["SOCCER", "TENNIS", "NBA", "NFL"]):
        st = status(s)
        flag = "ALLOWED" if st["standalone_allowed"] else "BLOCKED"
        print(f"{s:<8} {flag:<8} measured={st['measured']}  {st['reason']}")
